export const normalizeCategory = (value = '') => value.toString().trim().toLowerCase().replaceAll('_', '-').replace(/\s+/g, '-')

export const resolveCategoryValues = (value = '') => {
  const normalized = normalizeCategory(value)
  return categoryAliases[normalized] || categoryAliases[normalized.replaceAll('-', ' ')] || [value.toString().replaceAll('-', ' ').replace(/\b\w/g, (letter) => letter.toUpperCase())]
}

const categoryCount = (categoryName) => {
  const values = resolveCategoryValues(categoryName)
  return listingProperties.filter((property) => values.includes(property.category)).length
}

